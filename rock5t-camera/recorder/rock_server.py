class Handler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def _send(self, body, ctype="text/html"):
        if isinstance(body, str):
            body = body.encode()
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _json(self, obj):
        self._send(json.dumps(obj), "application/json")

    def do_GET(self):
        path, _, qs = self.path.partition("?")
        q = {k: urllib.parse.unquote_plus(v) for k, v in
             (p.split("=", 1) for p in qs.split("&") if "=" in p)}

        if path == "/":
            self._send(PAGE)
        elif path == "/files":
            self._send(FILES_PAGE)
        elif path == "/status":
            self._json({
                "recording": bool(_state["rec"]),
                "elapsed": int(time.time() - _state["rec_started"]) if _state["rec_started"] else 0,
                "name": _state["rec_name"] or "",
                "size": human(rec_bytes()),
                "storage": storage_info(),
            })
        elif path == "/start":
            with _state["lock"]:
                self._json(start_recording())
        elif path == "/stop":
            with _state["lock"]:
                self._json(stop_recording())
        elif path == "/api/files":
            self._json({"takes": list_takes(), "storage": storage_info(),
                        "usb": usb_targets(), "usb_avail": usb_candidates(),
                        "recording": bool(_state["rec"]), "xfer": _xfer})
        elif path == "/api/mount":
            self._json(mount_usb(q.get("dev", "")))
        elif path == "/api/umount":
            self._json(umount_usb())
        elif path == "/api/transfer":
            names = [n for n in q.get("names", "").split("|") if n]
            self._json(start_transfer(names, q.get("dest", "")))
        elif path == "/api/delete":
            names = [n for n in q.get("names", "").split("|") if n]
            with _state["lock"]:
                self._json(delete_takes(names))
        elif path.startswith("/dl/"):
            name = os.path.basename(urllib.parse.unquote(path[4:]))
            f = os.path.join(REC_DIR, name)
            if not os.path.isfile(f):
                self.send_error(404)
                return
            self.send_response(200)
            self.send_header("Content-Type", "video/x-matroska")
            self.send_header("Content-Length", str(os.path.getsize(f)))
            self.send_header("Content-Disposition", f"attachment; filename={name}")
            self.end_headers()
            try:
                with open(f, "rb") as fh:
                    shutil.copyfileobj(fh, self.wfile, 1 << 20)
            except (BrokenPipeError, ConnectionResetError):
                pass
        elif path in ("/preview0.mjpg", "/preview1.mjpg"):
            jpg_path = PREV_JPG[path[8]]
            self.send_response(200)
            self.send_header("Content-Type", "multipart/x-mixed-replace; boundary=frame")
            self.end_headers()
            try:
                while True:
                    try:
                        with open(jpg_path, "rb") as f:
                            jpg = f.read()
                    except FileNotFoundError:
                        jpg = b""
                    if jpg:
                        self.wfile.write(b"--frame\r\nContent-Type: image/jpeg\r\n"
                                         + f"Content-Length: {len(jpg)}\r\n\r\n".encode()
                                         + jpg + b"\r\n")
                    time.sleep(0.25)
            except (BrokenPipeError, ConnectionResetError):
                pass
        else:
            self.send_error(404)


