#!/usr/bin/env python3
"""
rock_server.py - web control panel for the ROCK 5T stereo recorder.

The Rock-side successor to the Orin's recorder/server.py, in the same visual
language, stripped to what the field needs: two live previews, one record
button, and a Manage Files page. Python stdlib only (no flask).

    sudo python3 rock_server.py     # http://<rock-ip>:8080  (root: mounts USB)
    # or let systemd run it at boot: see rock-recorder.service

No image-quality UI by design: exposure/colour live in the tuned IQ file
(/etc/iqfiles/imx477_RPI-HQ_default.json, generated by iqfiles/gen_imx477_iq.py)
and the sensor mode + bitrate are fixed at the rig's target (4K30, 28 Mbit).
One less thing to get wrong at a game; change the tuning, not the panel.

Design rules (each learned the hard way on this vendor stack):
  - Previews (both cams) run CONTINUOUSLY on the ISP selfpath at 1920x1080/5fps
    and are NEVER stopped or restarted - pipeline churn has locked this board
    up. Their crop selection is reset at start (stale-crop gotcha).
  - Recording runs on the mainpath - a different node, so previews keep running
    during a take. TWO independent files by design: fault isolation, and the
    stitcher pairs full-res frames by timestamp.
  - The record pipeline is the validated one: io-mode=dmabuf + an explicit
    framerate stamp (without it mpph265enc silently ignores bps) + CBR + a
    decoupling queue. Stop = SIGINT to the process group -> gst -e sends EOS ->
    finalized file.
  - Every gst child gets its own process group and is killed on exit; orphans
    otherwise keep the camera nodes open and silently black the next run.
"""

