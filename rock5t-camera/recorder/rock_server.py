# ----------------------------------------------------------------- helpers

def sh(cmd, timeout=30):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout)


def human(n):
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit in ("B", "KB") else f"{n:.1f} {unit}"
        n /= 1024.0
    return f"{n:.1f} TB"


def storage_info():
    try:
        st = os.statvfs(REC_DIR if os.path.isdir(REC_DIR) else f"/home/{PANEL_USER}")
    except OSError:
        return None
    total = st.f_blocks * st.f_frsize
    free = st.f_bavail * st.f_frsize
    used = total - free
    hours = free / (2 * BITRATE / 8 * 3600) if BITRATE else 0
    return {"total": human(total), "used": human(used), "free": human(free),
            "free_bytes": free, "pct": int(used / total * 100) if total else 0,
            "hours": round(hours, 1)}


MNT = "/mnt/usb"


def usb_candidates():
    """Unmounted removable partitions we could mount (nothing hardcoded)."""
    out = []
    r = sh("lsblk -J -o PATH,SIZE,FSTYPE,LABEL,MOUNTPOINT,TRAN,HOTPLUG,TYPE")
    try:
        tree = json.loads(r.stdout or "{}").get("blockdevices", [])
    except json.JSONDecodeError:
        return out

    def walk(nodes, removable=False):
        for n in nodes:
            rem = removable or n.get("tran") == "usb" or n.get("hotplug") in (True, "1")
            if (n.get("type") == "part" and rem and not n.get("mountpoint")
                    and n.get("fstype")):
                out.append({"dev": n.get("path"), "size": n.get("size"),
                            "fstype": n.get("fstype"),
                            "label": n.get("label") or os.path.basename(n.get("path", ""))})
            walk(n.get("children") or [], rem)

    walk(tree)
    return out


def mount_usb(dev):
    """Mount a removable partition at /mnt/usb. We run as root, so this is a
    direct call - but still refuse anything that is not a /dev/sdXN partition,
    so a bad request can never be aimed at the NVMe system disk."""
    if not re.fullmatch(r"/dev/sd[a-z][0-9]+", dev or ""):
        return {"ok": False, "msg": f"refusing '{dev}': not a /dev/sdXN partition"}
    if not os.path.exists(dev):
        return {"ok": False, "msg": f"no such device: {dev}"}
    os.makedirs(MNT, exist_ok=True)
    if sh(f"mountpoint -q {MNT}").returncode == 0:
        return {"ok": True, "msg": f"already mounted at {MNT}"}
    fstype = sh(f"lsblk -no FSTYPE {dev}").stdout.strip().splitlines()[:1]
    fstype = fstype[0] if fstype else ""
    # vfat/exfat/ntfs carry no unix ownership: map them to the panel user so
    # the takes are readable over ssh too
    if fstype in ("exfat", "vfat", "ntfs", "ntfs3"):
        uid = sh(f"id -u {PANEL_USER}").stdout.strip()
        gid = sh(f"id -g {PANEL_USER}").stdout.strip()
        opts = f"-o uid={uid},gid={gid},noatime"
    else:
        opts = "-o noatime"
    r = sh(f"mount {opts} {dev} {MNT}", timeout=45)
    if r.returncode != 0:
        return {"ok": False, "msg": (r.stderr or "mount failed").strip()[:300]}
    return {"ok": True, "msg": f"mounted {dev} ({fstype or 'auto'}) -> {MNT}"}


def umount_usb():
    sh("sync", timeout=60)
    r = sh(f"umount {MNT}", timeout=60)
    if r.returncode != 0:
        return {"ok": False, "msg": (r.stderr or "unmount failed - drive in use?").strip()[:300]}
    return {"ok": True, "msg": "unmounted - safe to unplug"}


def usb_targets():
    """Mounted removable drives we could offload to (auto-detected, no config)."""
    out = []
    try:
        with open("/proc/mounts") as f:
            for line in f:
                dev, mnt, fstype = (line.split() + ["", "", ""])[:3]
                mnt = mnt.replace("\\040", " ")
                if not dev.startswith("/dev/"):
                    continue
                if not (mnt.startswith("/media/") or mnt.startswith("/mnt/")):
                    continue
                if fstype in ("squashfs", "tmpfs", "devtmpfs"):
                    continue
                try:
                    st = os.statvfs(mnt)
                    free = st.f_bavail * st.f_frsize
                except OSError:
                    continue
                out.append({"path": mnt, "name": os.path.basename(mnt) or mnt,
                            "free": human(free), "free_bytes": free})
    except OSError:
        pass
    return out


# ----------------------------------------------------------------- previews

def start_previews():
    for cam, c in CAMS.items():
        sh(f"v4l2-ctl -d {c['self']} --set-selection "
           f"target=crop,top=0,left=0,width=3840,height=2160")
        try:
            os.remove(PREV_JPG[cam])
        except FileNotFoundError:
            pass
        pipeline = (f"gst-launch-1.0 v4l2src device={c['self']} ! "
                    f"video/x-raw,format=NV12,width=1920,height=1080 ! videorate ! "
                    f"video/x-raw,framerate=5/1 ! jpegenc quality=80 ! "
                    f"multifilesink location={PREV_JPG[cam]}")
        log = open(f"/tmp/rec_prev{cam}.log", "w")
        # own process group: shell=True means Popen's pid is the shell, so only
        # killpg reaches gst - otherwise previews outlive the server and hold
        # the selfpath nodes, blacking the next run
        _state["gst"][cam] = subprocess.Popen(pipeline, shell=True, stdout=log,
                                              stderr=log, preexec_fn=os.setsid)


def stop_previews():
    for p in _state["gst"].values():
        if p and p.poll() is None:
            try:
                os.killpg(os.getpgid(p.pid), signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                pass
    _state["gst"] = {}


# ---------------------------------------------------------------- recording

def start_recording():
    if _state["rec"]:
        return {"ok": False, "msg": "already recording"}
    os.makedirs(REC_DIR, exist_ok=True)
    name = time.strftime("take_%Y%m%d_%H%M%S")
    for cam, c in CAMS.items():
        f = os.path.join(REC_DIR, f"{name}_cam{cam}.mkv")
        pipeline = (f"gst-launch-1.0 -e v4l2src device={c['main']} io-mode=dmabuf ! "
                    f"video/x-raw,format=NV12,width=3840,height=2160 ! videorate ! "
                    f"video/x-raw,framerate=30/1 ! "
                    f"queue max-size-buffers=8 max-size-time=0 max-size-bytes=0 ! "
                    f"mpph265enc rc-mode=cbr bps={BITRATE} bps-max={BITRATE * 3 // 2} ! "
                    f"h265parse ! matroskamux ! filesink location={f}")
        log = open(f"/tmp/rec_cam{cam}.log", "w")
        _state["rec"][cam] = subprocess.Popen(pipeline, shell=True, stdout=log,
                                              stderr=log, preexec_fn=os.setsid)
    _state["rec_name"] = name
    _state["rec_started"] = time.time()

    # a pipeline whose device is held dies instantly and leaves a 0-byte file:
    # catch it and say why, rather than listing empty takes
    time.sleep(2)
    dead = []
    for cam, p in _state["rec"].items():
        if p.poll() is not None:
            tail = ""
            try:
                with open(f"/tmp/rec_cam{cam}.log") as fh:
                    lines = [ln for ln in fh.read().splitlines() if ln.strip()]
                tail = " | ".join(lines[-3:])
            except OSError:
                pass
            dead.append(f"cam{cam} pipeline died: {tail[:300]}")
    if dead:
        for cam, p in _state["rec"].items():
            if p.poll() is None:
                os.killpg(os.getpgid(p.pid), signal.SIGINT)
        for f in glob.glob(os.path.join(REC_DIR, f"{name}_cam*.mkv")):
            if os.path.getsize(f) == 0:
                os.remove(f)
        _state["rec"] = {}
        _state["rec_name"] = None
        _state["rec_started"] = None
        return {"ok": False, "msg": "; ".join(dead)}
    return {"ok": True, "msg": f"recording {name}"}


def stop_recording():
    if not _state["rec"]:
        return {"ok": False, "msg": "not recording"}
    for p in _state["rec"].values():
        if p.poll() is None:
            os.killpg(os.getpgid(p.pid), signal.SIGINT)   # gst -e: EOS + finalize
    warn = []
    for cam, p in _state["rec"].items():
        try:
            p.wait(timeout=20)
        except subprocess.TimeoutExpired:
            os.killpg(os.getpgid(p.pid), signal.SIGKILL)
            warn.append(f"cam{cam} force-stopped")
    name = _state["rec_name"]
    _state["rec"] = {}
    _state["rec_name"] = None
    _state["rec_started"] = None
    files = sorted(glob.glob(os.path.join(REC_DIR, f"{name}_cam*.mkv")))
    # created by a root process: give them to the panel user so ssh/scp and
    # manual cleanup do not need sudo
    try:
        uid = int(sh(f"id -u {PANEL_USER}").stdout.strip())
        gid = int(sh(f"id -g {PANEL_USER}").stdout.strip())
        for f in files:
            os.chown(f, uid, gid)
    except (ValueError, OSError):
        pass
    sizes = [f"{os.path.basename(f)} {human(os.path.getsize(f))}" for f in files]
    return {"ok": True, "msg": "saved " + ", ".join(sizes) + ("; " + "; ".join(warn) if warn else "")}


def rec_bytes():
    if not _state["rec_name"]:
        return 0
    return sum(os.path.getsize(f) for f in
               glob.glob(os.path.join(REC_DIR, f"{_state['rec_name']}_cam*.mkv"))
               if os.path.exists(f))


def list_takes():
    out = []
    for f in sorted(glob.glob(os.path.join(REC_DIR, "*.mkv")), reverse=True):
        stt = os.stat(f)
        out.append({"name": os.path.basename(f), "size": human(stt.st_size),
                    "bytes": stt.st_size,
                    "date": time.strftime("%Y-%m-%d %H:%M", time.localtime(stt.st_mtime))})
    return out


# ----------------------------------------------------------------- transfer

def _xfer_worker(names, dest):
    try:
        target = os.path.join(dest, "rock-recordings")
        os.makedirs(target, exist_ok=True)
        srcs = [os.path.join(REC_DIR, n) for n in names
                if os.path.isfile(os.path.join(REC_DIR, n))]
        total = sum(os.path.getsize(s) for s in srcs) or 1
        moved = 0
        for s in srcs:
            _xfer["file"] = os.path.basename(s)
            tmp = os.path.join(target, os.path.basename(s) + ".part")
            with open(s, "rb") as fi, open(tmp, "wb") as fo:
                while True:
                    chunk = fi.read(4 << 20)
                    if not chunk:
                        break
                    fo.write(chunk)
                    moved += len(chunk)
                    _xfer["pct"] = int(moved / total * 100)
            os.replace(tmp, os.path.join(target, os.path.basename(s)))
            if os.path.getsize(os.path.join(target, os.path.basename(s))) != os.path.getsize(s):
                raise OSError(f"size mismatch after copying {os.path.basename(s)}")
            _xfer["count"] += 1
        sh(f"sync")
        _xfer["pct"] = 100
    except Exception as ex:                                  # noqa: BLE001
        _xfer["error"] = repr(ex)
    finally:
        _xfer["active"] = False
        _xfer["done"] = True


def start_transfer(names, dest):
    if _xfer["active"]:
        return {"ok": False, "msg": "a transfer is already running"}
    if _state["rec"]:
        return {"ok": False, "msg": "not while recording"}
    if not names:
        return {"ok": False, "msg": "nothing selected"}
    if not dest or not os.path.isdir(dest):
        return {"ok": False, "msg": "no destination drive"}
    _xfer.update({"active": True, "pct": 0, "file": "", "done": False,
                  "error": None, "count": 0})
    threading.Thread(target=_xfer_worker, args=(names, dest), daemon=True).start()
    return {"ok": True, "msg": f"copying {len(names)} file(s)"}


def delete_takes(names):
    if _state["rec"]:
        return {"ok": False, "msg": "not while recording"}
    n = 0
    for name in names:
        p = os.path.join(REC_DIR, os.path.basename(name))
        if os.path.isfile(p) and p.startswith(os.path.realpath(REC_DIR)):
            os.remove(p)
            n += 1
    return {"ok": True, "msg": f"deleted {n} file(s)"}


